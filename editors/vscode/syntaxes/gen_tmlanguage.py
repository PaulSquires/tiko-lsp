"""Generates tiko.tmLanguage.json beside this file:  python gen_tmlanguage.py

The word lists are read from the Zed highlights query, so the two editors
colour the same words: the `#match?` keyword list and the built-in type list.
Re-run it whenever that list changes.
"""
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HL = os.path.join(HERE, '..', '..', 'zed', 'languages', 'tiko', 'highlights.scm')
OUT = os.path.join(HERE, 'tiko.tmLanguage.json')

hl = io.open(HL, encoding='utf-8').read()
lists = re.findall(r'"\^\(\?i\)\(([^"]*)\)\$"', hl)
assert len(lists) == 3, len(lists)
reserved = lists[0].split('|')
builtin_types = lists[1].split('|')
# The predeclared constants -- `nullptr` -- the third list, coloured as a language constant.
constants = lists[2].split('|')

# Structural words: the ones the grammar knows because they open or close blocks.
structural = ('sub function property constructor destructor operator declare type union enum '
              'namespace extern scope with asm if then else elseif endif select case is for to '
              'step next while wend do loop until exit continue end as of extends field explicit '
              'once private public protected static shared const virtual abstract byref byval '
              'return goto gosub class interface inherits implements partial').split()

control = set('if then else elseif endif select case for to step next while wend do loop until '
              'exit continue end return goto gosub'.split())
modifiers = set('private public protected static shared const virtual abstract byref byval '
                'explicit extends'.split())

def alt(words):
    # longest first, so `andalso` is tried before `and`
    return '|'.join(sorted(set(words), key=lambda w: (-len(w), w)))

kw_control = alt(w for w in structural if w in control)
kw_modifier = alt(modifiers)
kw_decl = alt(w for w in structural if w not in control and w not in modifiers)
other = alt(w for w in reserved if w not in set(structural) and w not in set(builtin_types))
types = alt(builtin_types)

g = {
    "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    "name": "Tiko",
    "scopeName": "source.tiko",
    "comment": "Generated by gen_tmlanguage.py from the Zed highlights query. tiko is "
               "case-insensitive, so every word pattern is (?i). The server's semantic "
               "tokens refine this once it is running.",
    "patterns": [
        {"include": "#comments"},
        {"include": "#preprocessor"},
        {"include": "#strings"},
        {"include": "#numbers"},
        {"include": "#declarations"},
        {"include": "#keywords"},
        {"include": "#calls"},
        {"include": "#operators"},
    ],
    "repository": {
        "comments": {
            "patterns": [
                {"name": "comment.block.tiko", "begin": "/'", "end": "'/",
                 "patterns": [{"include": "#comments"}]},
                {"name": "comment.line.apostrophe.tiko", "match": "'.*$"},
                {"name": "comment.line.rem.tiko", "match": r"(?i)(?<![\w.])rem(?=\s|$).*$"},
            ]
        },
        "preprocessor": {
            "patterns": [
                {"match": r'(?i)^\s*(#\s*(?:include|import))\b(\s+once\b)?\s*("[^"]*")?',
                 "captures": {"1": {"name": "keyword.control.directive.tiko"},
                              "2": {"name": "keyword.control.directive.tiko"},
                              "3": {"name": "string.quoted.double.include.tiko"}}},
                {"match": r'(?i)^\s*(#\s*(?:define|macro))\s+([A-Za-z_][A-Za-z0-9_]*)',
                 "captures": {"1": {"name": "keyword.control.directive.tiko"},
                              "2": {"name": "entity.name.function.preprocessor.tiko"}}},
                {"name": "keyword.control.directive.tiko",
                 "match": r'(?i)^\s*#\s*[A-Za-z_]+'},
            ]
        },
        "strings": {
            "patterns": [
                {"name": "string.quoted.double.escaped.tiko", "begin": '!"', "end": '"(?!")',
                 "patterns": [{"name": "constant.character.escape.tiko", "match": r'\\.|""'}]},
                {"name": "string.quoted.double.tiko", "begin": '\\$?"', "end": '"(?!")',
                 "patterns": [{"name": "constant.character.escape.tiko", "match": '""'}]},
            ]
        },
        "numbers": {
            "patterns": [
                {"name": "constant.numeric.hex.tiko", "match": r'(?i)&h[0-9a-f]+[ul]*'},
                {"name": "constant.numeric.binary.tiko", "match": r'(?i)&b[01]+[ul]*'},
                {"name": "constant.numeric.octal.tiko", "match": r'(?i)&o?[0-7]+[ul]*'},
                {"name": "constant.numeric.decimal.tiko",
                 "match": r'(?i)(?<![\w.])\d+(\.\d*)?(e[+-]?\d+)?[!#%&ful]*\b'},
                {"name": "constant.language.boolean.tiko", "match": r'(?i)\b(true|false)\b'},
                {"name": "constant.language.null.tiko",
                 "match": r'(?i)(?<![\w.])(' + alt(constants) + r')(?![\w$%&!#])'},
            ]
        },
        "declarations": {
            "patterns": [
                {"match": r'(?i)\b(sub|function|property|constructor|destructor|operator)\s+([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)',
                 "captures": {"1": {"name": "storage.type.function.tiko"},
                              "2": {"name": "entity.name.function.tiko"}}},
                {"match": r'(?i)^\s*(type|union|enum|class|interface)\s+([A-Za-z_][A-Za-z0-9_]*)',
                 "captures": {"1": {"name": "storage.type.tiko"},
                              "2": {"name": "entity.name.type.tiko"}}},
                {"match": r'(?i)\b(namespace)\s+([A-Za-z_][A-Za-z0-9_.]*)',
                 "captures": {"1": {"name": "storage.type.namespace.tiko"},
                              "2": {"name": "entity.name.namespace.tiko"}}},
            ]
        },
        "keywords": {
            "patterns": [
                # `select channel` (std/tasks): `channel` is no keyword elsewhere -- `ch as
                # Channel( of T )` -- so it is coloured only as the select's second word.
                {"match": r'(?i)(?<![\w.])(select)\s+(channel)(?![\w$%&!#])',
                 "captures": {"1": {"name": "keyword.control.tiko"},
                              "2": {"name": "keyword.control.tiko"}}},
                # A property's sections, `get` / `set` alone on their line and `end get` /
                # `end set`: neither word is reserved -- `set` names containers.Set -- so
                # only there.
                {"match": r"(?i)^\s*(get|set)\s*(?=$|')",
                 "captures": {"1": {"name": "keyword.other.tiko"}}},
                {"match": r'(?i)(?<![\w.])(end)\s+(get|set)(?![\w$%&!#])',
                 "captures": {"1": {"name": "keyword.control.tiko"},
                              "2": {"name": "keyword.other.tiko"}}},
                {"name": "keyword.control.tiko", "match": r'(?i)(?<![\w.])(' + kw_control + r')(?![\w$%&!#])'},
                {"name": "storage.modifier.tiko", "match": r'(?i)(?<![\w.])(' + kw_modifier + r')(?![\w$%&!#])'},
                {"name": "storage.type.tiko", "match": r'(?i)(?<![\w.])(' + types + r')(?![\w$%&!#])'},
                {"name": "keyword.other.tiko", "match": r'(?i)(?<![\w.])(' + kw_decl + r')(?![\w$%&!#])'},
                {"name": "support.function.builtin.tiko", "match": r'(?i)(?<![\w.])(' + other + r')(?![\w$%&!#])'},
            ]
        },
        "calls": {
            "patterns": [
                {"match": r'([A-Za-z_][A-Za-z0-9_]*)\s*(?=\()',
                 "captures": {"1": {"name": "entity.name.function.call.tiko"}}},
            ]
        },
        "operators": {
            "patterns": [
                {"name": "keyword.operator.tiko", "match": r'(?i)->|[-+*/\\^&=<>@]|\b(mod|and|or|xor|not|shl|shr|andalso|orelse|eqv|imp)\b'},
            ]
        },
    },
}

io.open(OUT, 'w', encoding='utf-8', newline='\n').write(json.dumps(g, indent=2) + '\n')
print('wrote', OUT, '-', len(reserved), 'reserved words,', len(builtin_types), 'built-in types')
