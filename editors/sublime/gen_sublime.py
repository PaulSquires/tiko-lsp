"""Generates Tiko.sublime-syntax and "Indentation Rules.tmPreferences" beside this file.

    python gen_sublime.py

Both are DERIVED, so the three editors agree:

  * the word lists come from the Zed highlights query
    (../zed/languages/tiko/highlights.scm) -- the `#match?` keyword list and the
    built-in type list -- exactly as ../vscode/syntaxes/gen_tmlanguage.py reads them;
  * the indent patterns come from ../vscode/language-configuration.json.

Re-run it whenever either changes.
"""
import io
import json
import os
import re
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
HL = os.path.join(HERE, '..', 'zed', 'languages', 'tiko', 'highlights.scm')
LANGCFG = os.path.join(HERE, '..', 'vscode', 'language-configuration.json')

# ---- the word lists ----------------------------------------------------------
hl = io.open(HL, encoding='utf-8').read()
lists = re.findall(r'"\^\(\?i\)\(([^"]*)\)\$"', hl)
assert len(lists) == 3, len(lists)
reserved, builtin_types = lists[0].split('|'), lists[1].split('|')
# The predeclared constants -- `nullptr` -- the third list, coloured as a language constant.
constants = lists[2].split('|')

structural = ('sub function property constructor destructor operator declare type union enum '
              'namespace extern scope with asm if then else elseif endif select case is for to '
              'step next while wend do loop until exit continue end as of extends field explicit '
              'once private public protected static shared const virtual abstract byref byval '
              'return goto gosub class interface inherits implements partial').split()
control = set('if then else elseif endif select case for to step next while wend do loop until '
              'exit continue end return goto gosub'.split())
modifiers = set('private public protected static shared const virtual abstract byref byval '
                'explicit extends'.split())


def alt(words):
    return '|'.join(sorted(set(words), key=lambda w: (-len(w), w)))


kw_control = alt(w for w in structural if w in control)
kw_modifier = alt(modifiers)
kw_decl = alt(w for w in structural if w not in control and w not in modifiers)
other = alt(w for w in reserved if w not in set(structural) and w not in set(builtin_types))
types = alt(builtin_types)

WORD_END = r'(?![\w$%&!#])'
WORD_START = r'(?<![\w.])'


def q(s):
    """A YAML single-quoted scalar."""
    return "'" + s.replace("'", "''") + "'"


# ---- Tiko.sublime-syntax -------------------------------------------------------
lines = []
w = lines.append
w('%YAML 1.2')
w('---')
w('# GENERATED by gen_sublime.py from the Zed highlights query -- do not edit by hand.')
w('# tiko is case-insensitive, so every word pattern is (?i). The server\'s semantic')
w('# tokens refine this once LSP-tiko is running.')
w('name: Tiko')
w('scope: source.tiko')
w('file_extensions: [tiko, tko, ti, bas, bi, inc]')
w('')
w('contexts:')
w('  main:')
for inc in ('comments', 'preprocessor', 'strings', 'numbers', 'declarations', 'keywords', 'calls', 'operators'):
    w('    - include: ' + inc)
w('')
w('  comments:')
w("    - match: \"/'\"")
w('      scope: punctuation.definition.comment.begin.tiko')
w('      push: block-comment')
w("    - match: \"'.*$\"")
w('      scope: comment.line.apostrophe.tiko')
w('    - match: ' + q(r'(?i)(?<![\w.])rem(?=\s|$).*$'))
w('      scope: comment.line.rem.tiko')
w('')
w('  block-comment:')
w('    - meta_scope: comment.block.tiko')
w("    - match: \"'/\"")
w('      scope: punctuation.definition.comment.end.tiko')
w('      pop: true')
w("    - match: \"/'\"")
w('      push: block-comment')
w('')
w('  preprocessor:')
w('    - match: ' + q(r'(?i)^\s*(#\s*(?:include|import))\b(\s+once\b)?\s*("[^"]*")?'))
w('      captures:')
w('        1: keyword.control.directive.tiko')
w('        2: keyword.control.directive.tiko')
w('        3: string.quoted.double.include.tiko')
w('    - match: ' + q(r'(?i)^\s*(#\s*(?:define|macro))\s+([A-Za-z_][A-Za-z0-9_]*)'))
w('      captures:')
w('        1: keyword.control.directive.tiko')
w('        2: entity.name.function.preprocessor.tiko')
w('    - match: ' + q(r'(?i)^\s*#\s*[A-Za-z_]+'))
w('      scope: keyword.control.directive.tiko')
w('')
w('  strings:')
w("    - match: '!\"'")
w('      scope: punctuation.definition.string.begin.tiko')
w('      push: escaped-string')
w('    - match: ' + q(r'\$?"'))
w('      scope: punctuation.definition.string.begin.tiko')
w('      push: string')
w('')
w('  escaped-string:')
w('    - meta_scope: string.quoted.double.escaped.tiko')
w('    - match: ' + q(r'\\.|""'))
w('      scope: constant.character.escape.tiko')
w('    - match: ' + q('"'))
w('      scope: punctuation.definition.string.end.tiko')
w('      pop: true')
w('    - match: \'$\'')
w('      pop: true')
w('')
w('  string:')
w('    - meta_scope: string.quoted.double.tiko')
w("    - match: '\"\"'")
w('      scope: constant.character.escape.tiko')
w('    - match: ' + q('"'))
w('      scope: punctuation.definition.string.end.tiko')
w('      pop: true')
w('    - match: \'$\'')
w('      pop: true')
w('')
w('  numbers:')
w('    - match: ' + q(r'(?i)&h[0-9a-f]+[ul]*'))
w('      scope: constant.numeric.hex.tiko')
w('    - match: ' + q(r'(?i)&b[01]+[ul]*'))
w('      scope: constant.numeric.binary.tiko')
w('    - match: ' + q(r'(?i)&o?[0-7]+[ul]*'))
w('      scope: constant.numeric.octal.tiko')
w('    - match: ' + q(r'(?i)(?<![\w.])\d+(\.\d*)?(e[+-]?\d+)?[!#%&ful]*\b'))
w('      scope: constant.numeric.decimal.tiko')
w('    - match: ' + q(r'(?i)\b(true|false)\b'))
w('      scope: constant.language.boolean.tiko')
w('    - match: ' + q(r'(?i)(?<![\w.])(' + alt(constants) + r')(?![\w$%&!#])'))
w('      scope: constant.language.null.tiko')
w('')
w('  declarations:')
w('    - match: ' + q(r'(?i)\b(sub|function|property|constructor|destructor|operator)\s+([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)'))
w('      captures:')
w('        1: storage.type.function.tiko')
w('        2: entity.name.function.tiko')
w('    - match: ' + q(r'(?i)^\s*(type|union|enum|class|interface)\s+([A-Za-z_][A-Za-z0-9_]*)'))
w('      captures:')
w('        1: storage.type.tiko')
w('        2: entity.name.type.tiko')
w('    - match: ' + q(r'(?i)\b(namespace)\s+([A-Za-z_][A-Za-z0-9_.]*)'))
w('      captures:')
w('        1: storage.type.namespace.tiko')
w('        2: entity.name.namespace.tiko')
w('')
w('  keywords:')
# `select channel` (std/tasks): `channel` is no keyword elsewhere, so only here.
w('    - match: ' + q(r'(?i)' + WORD_START + r'(select)\s+(channel)' + WORD_END))
w('      captures:')
w('        1: keyword.control.tiko')
w('        2: keyword.control.tiko')
# A property's sections, `get` / `set` alone on their line and `end get` / `end set`: neither
# word is reserved -- `set` names containers.Set -- so only there.
w('    - match: ' + q(r"(?i)^\s*(get|set)\s*(?=$|')"))
w('      captures:')
w('        1: keyword.other.tiko')
w('    - match: ' + q(r'(?i)' + WORD_START + r'(end)\s+(get|set)' + WORD_END))
w('      captures:')
w('        1: keyword.control.tiko')
w('        2: keyword.other.tiko')
for scope, words in (('keyword.control.tiko', kw_control), ('storage.modifier.tiko', kw_modifier),
                     ('storage.type.tiko', types), ('keyword.other.tiko', kw_decl),
                     ('support.function.builtin.tiko', other)):
    w('    - match: ' + q('(?i)' + WORD_START + '(' + words + ')' + WORD_END))
    w('      scope: ' + scope)
w('')
w('  calls:')
w('    - match: ' + q(r'([A-Za-z_][A-Za-z0-9_]*)\s*(?=\()'))
w('      captures:')
w('        1: variable.function.tiko')
w('')
w('  operators:')
w('    - match: ' + q(r'(?i)->|[-+*/\\^&=<>@]|\b(mod|and|or|xor|not|shl|shr|andalso|orelse|eqv|imp)\b'))
w('      scope: keyword.operator.tiko')

io.open(os.path.join(HERE, 'Tiko.sublime-syntax'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')

# ---- Indentation Rules.tmPreferences ---------------------------------------------
cfg = json.load(io.open(LANGCFG, encoding='utf-8'))
rules = cfg['indentationRules']
prefs = """<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by gen_sublime.py from ../vscode/language-configuration.json -- do not edit by hand. -->
<plist version="1.0">
<dict>
    <key>scope</key>
    <string>source.tiko</string>
    <key>settings</key>
    <dict>
        <key>increaseIndentPattern</key>
        <string>{inc}</string>
        <key>decreaseIndentPattern</key>
        <string>{dec}</string>
    </dict>
</dict>
</plist>
""".format(inc=escape(rules['increaseIndentPattern']), dec=escape(rules['decreaseIndentPattern']))
io.open(os.path.join(HERE, 'Indentation Rules.tmPreferences'), 'w', encoding='utf-8', newline='\n').write(prefs)

print('wrote Tiko.sublime-syntax ({} reserved words, {} built-in types) and Indentation Rules.tmPreferences'
      .format(len(reserved), len(builtin_types)))
