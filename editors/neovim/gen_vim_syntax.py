"""Generates syntax/tiko.vim beside this file:  python gen_vim_syntax.py

The word lists come from the Zed highlights query
(../zed/languages/tiko/highlights.scm) -- the `#match?` keyword list and the
built-in type list -- exactly as the VS Code and Sublime generators read them,
so every editor colours the same words. Re-run it whenever that list changes.
Once the server is running, Neovim's LSP semantic tokens refine the colours.
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HL = os.path.join(HERE, '..', 'zed', 'languages', 'tiko', 'highlights.scm')
OUT = os.path.join(HERE, 'syntax', 'tiko.vim')

hl = io.open(HL, encoding='utf-8').read()
lists = re.findall(r'"\^\(\?i\)\(([^"]*)\)\$"', hl)
assert len(lists) == 3, len(lists)
reserved, builtin_types = lists[0].split('|'), lists[1].split('|')
# The predeclared constants -- `nullptr` -- the third list, linked to Constant.
constants = lists[2].split('|')

structural = ('sub function property constructor destructor operator declare type union enum '
              'namespace extern scope with asm if then else elseif endif select case is for to '
              'step next while wend do loop until exit continue end as of extends field explicit '
              'once private public protected static shared const virtual abstract byref byval '
              'return goto gosub').split()
control = set('if then else elseif endif select case for to step next while wend do loop until '
              'exit continue end return goto gosub'.split())
modifiers = set('private public protected static shared const virtual abstract byref byval '
                'explicit extends'.split())
operators = set('mod and or xor not shl shr andalso orelse eqv imp'.split())


def words(ws, per_line=10):
    ws = sorted(set(ws))
    return [' '.join(ws[i:i + per_line]) for i in range(0, len(ws), per_line)]


groups = [
    ('tikoControl', [w for w in structural if w in control]),
    ('tikoModifier', sorted(modifiers)),
    ('tikoDeclare', [w for w in structural if w not in control and w not in modifiers]),
    ('tikoType', builtin_types),
    ('tikoOperatorWord', sorted(operators)),
    # Not `rem`: a keyword beats a match at the same position in Vim, so `rem`
    # as a keyword would colour a REM comment as a word instead of a comment.
    ('tikoBuiltin', [w for w in reserved
                     if w not in set(structural) and w not in set(builtin_types)
                     and w not in operators and w != 'rem']),
]

out = []
w = out.append
w('" Vim syntax file for tiko -- the FreeBASIC-compatible language of tiko-lang.')
w('" GENERATED by gen_vim_syntax.py from the Zed highlights query: do not edit by hand.')
w('" tiko is case-insensitive. LSP semantic tokens refine this once tiko-lsp is running.')
w('')
w('if exists("b:current_syntax")')
w('  finish')
w('endif')
w('')
w('syntax case ignore')
w('')
for group, ws in groups:
    for line in words(ws):
        w('syn keyword {} {}'.format(group, line))
w('')
w('" Comments: an apostrophe, REM as a whole word, and the nesting block form.')
w('syn keyword tikoTodo contained TODO FIXME XXX NOTE')
w('syn match   tikoComment "\'.*$" contains=tikoTodo')
w('syn match   tikoComment "\\<rem\\>.*$" contains=tikoTodo')
w('syn region  tikoBlockComment start="/\'" end="\'/" contains=tikoBlockComment,tikoTodo')
w('')
w('" Strings: "" is an escaped quote; !"..." is the escape-sequence form.')
w('syn region  tikoString start=+\\$\\="+ skip=+""+ end=+"+ oneline')
w('syn region  tikoString start=+!"+ skip=+\\\\.\\|""+ end=+"+ oneline contains=tikoEscape')
w('syn match   tikoEscape contained +\\\\.+')
w('')
w('" Numbers: &h / &b / &o and decimals with an optional exponent and suffix.')
w('syn match   tikoNumber "&h\\x\\+[ul]*"')
w('syn match   tikoNumber "&b[01]\\+[ul]*"')
w('syn match   tikoNumber "&o\\=\\o\\+[ul]*"')
w('syn match   tikoNumber "\\<\\d\\+\\(\\.\\d*\\)\\=\\(e[+-]\\=\\d\\+\\)\\=[!#%&ful]*"')
w('syn keyword tikoBoolean true false')
w('syn keyword tikoNull ' + ' '.join(constants))
w('')
w('" Preprocessor directives, and the path an #include or #import names.')
w('syn match   tikoPreProc "^\\s*#\\s*\\a\\+"')
w('syn match   tikoInclude "^\\s*#\\s*\\(include\\|import\\)\\>.*$" contains=tikoPreProcWord,tikoString')
w('syn match   tikoPreProcWord contained "#\\s*\\a\\+\\(\\s\\+once\\>\\)\\="')
w('')
w('" The name a procedure or a type declares.')
w('syn match   tikoFunctionName "\\(\\<\\(sub\\|function\\|property\\|constructor\\|destructor\\|operator\\)\\s\\+\\)\\@<=\\h\\w*\\(\\.\\h\\w*\\)*"')
w('syn match   tikoTypeName "\\(^\\s*\\(type\\|union\\|enum\\)\\s\\+\\)\\@<=\\h\\w*"')
w('')
for a, b in (('tikoControl', 'Conditional'), ('tikoModifier', 'StorageClass'), ('tikoDeclare', 'Keyword'),
             ('tikoType', 'Type'), ('tikoOperatorWord', 'Operator'), ('tikoBuiltin', 'Function'),
             ('tikoTodo', 'Todo'), ('tikoComment', 'Comment'), ('tikoBlockComment', 'Comment'),
             ('tikoString', 'String'), ('tikoEscape', 'SpecialChar'), ('tikoNumber', 'Number'),
             ('tikoBoolean', 'Boolean'), ('tikoNull', 'Constant'), ('tikoPreProc', 'PreProc'), ('tikoInclude', 'Include'),
             ('tikoPreProcWord', 'PreProc'), ('tikoFunctionName', 'Function'), ('tikoTypeName', 'Type')):
    w('hi def link {:<17} {}'.format(a, b))
w('')
w('let b:current_syntax = "tiko"')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('wrote', OUT, '-', len(reserved), 'reserved words,', len(builtin_types), 'built-in types')
